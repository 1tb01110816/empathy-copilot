// 会话级兜底：没命中任何规则时的弱规则
const FALLBACK = { major: '综合咨询', minor: '一般咨询', intent: '一般咨询', re: /(你好|在吗|咨询|问一下|请问)/ };

export function classifyText(text) {
  if (!text) return null;
  const t = String(text);
  let best = null;
  for (const rule of SCENE_RULES) {
    if (rule.re.test(t)) {
      if (!best) best = rule;
    }
  }
  if (!best && FALLBACK.re.test(t)) best = FALLBACK;
  if (!best) return null;
  return { major: best.major, minor: best.minor, intent: best.intent, sceneKey: `${best.major}/${best.minor}`, w: best.w || 1 };
}

// 会话级意图序列：买家消息逐条分类，输出意图时间线与主场景
// dominant 计分 = 消息数 × 规则权重；同分按出现先后；其他场景存在时忽略“综合咨询”兜底
export function sessionIntents(messages) {
  const timeline = [];
  for (const m of messages) {
    if (!m.isBuyer) continue;
    const c = classifyText(m.text);
    timeline.push({ seq: m.seq, ...(c || { major: '', minor: '', intent: '未识别', sceneKey: '', w: 0 }) });
  }
  const agg = new Map();
  let i = 0;
  for (const t of timeline) {
    if (!t.sceneKey) continue;
    if (!agg.has(t.sceneKey)) agg.set(t.sceneKey, { count: 0, score: 0, order: i++ });
    const a = agg.get(t.sceneKey);
    a.count += 1;
    a.score += t.w || 1;
  }
  let dominant = [...agg.entries()]
    .map(([key, a]) => {
      const [major, minor] = key.split('/');
      return { major, minor, count: a.count, score: Math.round(a.score * 100) / 100, order: a.order };
    })
    .sort((a, b) => b.score - a.score || a.order - b.order);
  if (dominant.some((d) => d.major !== '综合咨询')) dominant = dominant.filter((d) => d.major !== '综合咨询');
  const switched = new Set(timeline.filter((t) => t.sceneKey).map((t) => t.sceneKey)).size > 1;
  return { timeline, dominant, switched };
}
