export function matchWords(text, words) {
  const hits = [];
  let rest = text;
  for (const w of [...words].sort((a, b) => b.length - a.length)) {
    let i = rest.indexOf(w);
    // 纯数字词（如 315）避免命中长数字串内部（如订单号 ...683315）
    if (i >= 0 && /^\d+$/.test(w)) {
      let from = i + 1;
      while (i >= 0 && (/[\d\u0000]/.test(rest[i - 1] || '') || /[\d\u0000]/.test(rest[i + w.length] || ''))) {
        i = rest.indexOf(w, from);
        from = i + 1;
      }
    }
    if (i >= 0) {
      hits.push(w);
      rest = rest.slice(0, i) + '\u0000'.repeat(w.length) + rest.slice(i + w.length);
    }
  }
  return hits;
}

// 优先匹配：命中高优先级类别的词会从文本中移除，避免同一个词被多次计分
export function matchByPriority(text, categories) {
  const result = {};
  let rest = text;
  for (const cat of categories) {
    const hits = matchWords(rest, LEXICON[cat] || []);
    if (hits.length) {
      result[cat] = hits;
      for (const w of hits) rest = rest.split(w).join('\u0000'.repeat(w.length));
    }
  }
  return result;
}
